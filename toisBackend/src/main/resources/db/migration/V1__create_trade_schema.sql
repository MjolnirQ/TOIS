create function check_hall_trade_point()
returns trigger
as $$
begin
    if not exists (
        select 1
        from shop
        where trade_point_id = new.trade_point_id
    )
    and not exists (
        select 1
        from department_store
        where trade_point_id = new.trade_point_id
    ) then
        raise exception 'hall can reference only shop or department_store';
    end if;

    return new;
end;
$$ language plpgsql;

create function sync_trade_point_type_tables()
returns trigger
security definer
as $$
begin
    if tg_op = 'update' then
        if new.type = old.type then
            return new;
        end if;

        if new.type <> old.type
        and not (
            old.type in ('STALL', 'KIOSK')
            and new.type in ('STALL', 'KIOSK')
        ) then
            raise exception 'cannot change trade point type from % to %', old.type, new.type;
        end if;
    end if;

    delete from department_store
    where trade_point_id = new.id;

    delete from shop
    where trade_point_id = new.id;

    delete from stall
    where trade_point_id = new.id;

    delete from kiosk
    where trade_point_id = new.id;

    if new.type = 'DEPARTMENT_STORE' then
        insert into department_store (trade_point_id)
        values (new.id);

    elsif new.type = 'SHOP' then
        insert into shop (trade_point_id)
        values (new.id);

    elsif new.type = 'STALL' then
        insert into stall (trade_point_id)
        values (new.id);

    elsif new.type = 'KIOSK' then
        insert into kiosk (trade_point_id)
        values (new.id);
    end if;

    return new;
end;
$$ language plpgsql;

create trigger trg_check_hall
