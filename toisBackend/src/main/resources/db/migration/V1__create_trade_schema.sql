create function check_trade_point_before_sale_create()
returns trigger
security definer
as $$
begin
    if new.customer_id is not null and
        (
            exists (
                select 1
                from stall
                where trade_point_id = new.trade_point_id
            )
            or exists (
                select 1
                from kiosk
                where trade_point_id = new.trade_point_id
            )
        ) then
        raise exception 'cannot create sale in kiosk or stall with not-null customer';
    end if;

    return new;
end;
$$ language plpgsql;

create trigger trg_check_trade_point_before_sale_create
before insert
on sale
for each row
execute function check_trade_point_before_sale_create();

