create function sync_employee_position_tables()
returns trigger
security definer
as $$
begin
    delete from seller
    where employee_id = new.id;

    delete from section_manager
    where employee_id = new.id;

    delete from trade_manager
    where employee_id = new.id;

    if new.position = 'SELLER' then
        insert into seller (employee_id)
        values (new.id);

    elsif new.position = 'SECTION_MANAGER' then
        insert into section_manager (employee_id)
        values (new.id);

    elsif new.position = 'TRADE_MANAGER' then
        insert into trade_manager (employee_id)
        values (new.id);
    end if;

    return new;
end;
$$ language plpgsql;

create trigger trg_sync_employee_position_tables
after insert or update of position
on employee
for each row
execute function sync_employee_position_tables();

