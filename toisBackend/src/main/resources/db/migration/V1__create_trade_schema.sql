create function check_section_manager_assignment()
returns trigger
security definer
as $$
begin
    if not exists (
        select 1
        from section s
        where s.id = new.section_id
          and s.department_store_id = new.trade_point_id
    ) then
        raise exception 'section manager can be assigned only to section of the same department_store';
    end if;

    return new;
end;
$$ language plpgsql;

